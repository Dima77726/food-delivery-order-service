package com.dima.fooddelivery.live;

/**
 * Получатель сигналов: потоки клиента, доска ресторана, ожидающие курьеры.
 *
 * <p>Слушатель базы знает только этот интерфейс, а не конкретных получателей: новый вид живых
 * обновлений добавляется ещё одной реализацией, без правок слушателя.
 *
 * <p>{@link #onSignal} вызывается из единственного потока слушателя, поэтому реализации не
 * делают в нём ничего долгого — чтение базы и отправку клиентам они отдают своему исполнителю.
 */
public interface LiveChannel {

    void onSignal(LiveSignal signal);

    /** Сигналы могли потеряться (слушатель переподключался): догнать всех подписчиков из базы. */
    void resync();

    /** Закрыть все открытые соединения — сервис останавливается. */
    void closeAll();
}
