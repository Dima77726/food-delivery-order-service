-- Журнал аудита сам служит outbox для сводного журнала в insights-service.
--
-- Отдельная очередь не нужна: запись журнала уже ложится в транзакции действия, и всё, чего
-- ей не хватает для доставки, — отметка «отправлено». Копировать её в outbox значило бы
-- держать одни и те же данные дважды и следить, чтобы копии не разошлись.
--
-- Колонку заполняет только публикатор; содержимое записи по-прежнему не меняется никогда.
-- Записи, сделанные до миграции, получают NULL и уезжают первыми: история заказов
-- попадает в сводный журнал без отдельного переноса.
ALTER TABLE audit_log ADD COLUMN IF NOT EXISTS published_at TIMESTAMPTZ;

COMMENT ON COLUMN audit_log.published_at IS 'Когда запись подтверждена Kafka; NULL — ещё не отправлена в сводный журнал';

-- Частичный индекс: публикатор и метрика читают только неотправленное, и размер журнала
-- на них не влияет.
CREATE INDEX IF NOT EXISTS idx_audit_log_unpublished
    ON audit_log (id)
    WHERE published_at IS NULL;
